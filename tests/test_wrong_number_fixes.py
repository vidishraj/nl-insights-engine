class _StubProposer:
    """Feeds the recorded role claims into build_semantic_model — the discovery of the
    partition/returns/period structure still runs against the real data. An optional
    ``overrides`` dict changes individual column roles, to model a live proposer that (say)
    types the completeness column as 'ignore'."""

    name = "stub"

    def __init__(self, overrides: dict[str, tuple[str, str | None]] | None = None) -> None:
        self._claims = {**_CLAIMS, **(overrides or {})}

    def complete(self, request: LLMRequest) -> dict[str, Any]:
        return {
            "claims": [
                {"column": c, "role": r, "entity": e, "confidence": 0.9, "reasons": ["stub"]}
                for c, (r, e) in self._claims.items()
            ]
        }


