def test_non_product_disclosure_is_correct_and_truncated(syn) -> None:  # type: ignore[no-untyped-def]
    # A bare net_revenue total legitimately includes postage/fees; the disclosure must state,
    # in numbers, exactly what non-product money is inside it. Expectation comes from OUTSIDE the
    # disclosure path - an independent group-by over the raw column - so the test cannot be
    # pinned to the code it checks; it also matches the pre-registered baseline (6 non-PRODUCT
    # types, total +59,256.00, PRODUCT +11,514.00). The disclosure sums the bound measure over
    # the line_type string, drops null/zero groups, orders by absolute value, and names only the
    # top three with a "+N more" tail - so the assertion reflects the CODE's truncated form.
    con, model, t = syn
    ind = _gt(
        con,
        f"SELECT line_type, round(sum(line_revenue), 2) FROM {t} "
        f"WHERE line_type <> 'PRODUCT' AND line_type IS NOT NULL "
        f"AND line_revenue IS NOT NULL AND line_revenue <> 0 "
        f"GROUP BY line_type ORDER BY abs(sum(line_revenue)) DESC",
    )
    exp_count = len(ind)
    exp_total = round(sum(m for _, m in ind), 2)
    exp_top3 = [lt for lt, _ in ind[:3]]
    assert exp_count == 6 and exp_total == 59256.00  # the pre-registered baseline, independently
    assert exp_top3 == ["POSTAGE", "FEE", "CARRIAGE"]  # abs-desc order is deterministic
    assert _gt(con, f"SELECT round(sum(line_revenue), 2) FROM {t} WHERE line_type = 'PRODUCT'") == [
        (11514.0,)
    ]

    a = _ans(con, model, QueryIR(measures=["net_revenue"], group_by=[]))  # the real disclosure path
    disclosure = next((s for s in a.assumptions if "non-PRODUCT" in s), None)
    assert disclosure is not None  # a disclosure is emitted at all
    assert f"{exp_count} non-PRODUCT" in disclosure  # the count of non-zero non-fact groups
    assert f"{exp_total:+,.2f}" in disclosure  # the total, covering ALL groups, not just the named
    listed = disclosure.split("(", 1)[1]  # the parenthetical contributor list
    assert 0 <= listed.index("POSTAGE") < listed.index("FEE") < listed.index("CARRIAGE")  # pinned
    assert "+3 more" in disclosure  # truncated to three named; the total still covers all six
