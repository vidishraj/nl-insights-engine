def test_growth_clarify_and_answer_both_flow_through_run_query_pipeline(
    syn, tmp_path: Path
) -> None:  # type: ignore[no-untyped-def]
    # Prove the growth path end-to-end through the REAL interpret -> bind -> execute
    # pipeline (run_query), not by calling the compiler helper directly: an absent period
    # becomes a CLARIFY verdict, a present one an ANSWER carrying the growth column.
    from nl_insights.jobs.pipeline import run_query
    from nl_insights.jobs.store import Dataset

    con, model, t = syn
    con.close()  # run_query opens its own connection via dataset.connect()
    result = ingest(_SYNTHETIC, data_dir=tmp_path / ".data2", name="syn2")
    con2 = duckdb.connect(str(result.duckdb_path))
    model2 = build_semantic_model(con2, result.table, result.profile, _StubProposer())
    con2.close()
    dataset = Dataset(
        dataset_id="syn2",
        table=result.table,
        duckdb_path=str(result.duckdb_path),
        row_count=model2.row_count,
        model=model2,
    )

    class _InterpretStub:
        name = "stub"

        def __init__(self, ir: QueryIR) -> None:
            self._ir = ir

        def complete(self, request: LLMRequest) -> dict[str, Any]:
            return self._ir.model_dump()

    absent = QueryIR(
        measures=["net_revenue"],
        group_by=["country"],
        period_comparison=PeriodComparison(grain="quarter", period_a="2099-Q1", period_b="2099-Q2"),
    )
    r = run_query(
        dataset=dataset,
        question="growth 2099",
        previous_ir=None,
        provider=_InterpretStub(absent),
        model="m",
        emit=lambda *a, **k: None,
    )
    assert r.kind is VerdictKind.CLARIFY and "2099-Q1" in (r.clarify_question or "")

    present = QueryIR(
        measures=["net_revenue"],
        group_by=["country"],
        period_comparison=PeriodComparison(grain="quarter"),
        top_k=TopK(measure="growth", k=4),
    )
    r2 = run_query(
        dataset=dataset,
        question="which countries grew most",
        previous_ir=None,
        provider=_InterpretStub(present),
        model="m",
        emit=lambda *a, **k: None,
    )
    assert r2.answer is not None and "growth" in r2.answer.columns


# --- MAJ-alpha: a huge growth off a tiny base is disclosed with figures, not silently ranked
def test_growth_discloses_small_base_groups_with_figures(syn) -> None:  # type: ignore[no-untyped-def]
    con, model, t = syn
    a = _ans(
        con,
        model,
        QueryIR(
            measures=["net_revenue"],
            group_by=["country"],
            period_comparison=PeriodComparison(grain="quarter"),
            top_k=TopK(measure="growth", k=6),
        ),
    )
    # the synthetic data has a tiny-base country (Sark) that tops the ranking on a trivial base
    top = a.rows[0]
    assert top["country"] == "Sark" and top["growth"] > 1.0
    # ...and its small base is disclosed WITH the figure and its share of the base period,
    # rather than dropped (the user's call) — computed independently here.
    base_total = _gt(
        con,
        f"""SELECT sum(line_revenue) FROM {t}
            WHERE (strftime(invoice_date,'%Y')||'-Q'||CAST(quarter(invoice_date) AS VARCHAR))
                  = '2021-Q1'""",
    )[0][0]
    frac = top["period_a_value"] / base_total
    assert frac < 0.01  # genuinely a small base
    disclosure = next((x for x in a.assumptions if "base under" in x), None)
    assert disclosure is not None and "Sark" in disclosure and "volatile" in disclosure


# --- negative base: a % change over a negative base inverts its sign; NULL it, disclose it -
def test_growth_negative_base_is_not_ranked_and_disclosed_as_negative(syn) -> None:  # type: ignore[no-untyped-def]
    con, model, t = syn
    # the synthetic has a country (Tortuga) that recovers from a net-negative Q1 to a positive
    # Q2 — a genuine turnaround that (b-a)/a would report as a large DECLINE.
    for direction in ("desc", "asc"):
        a = _ans(
            con,
            model,
            QueryIR(
                measures=["net_revenue"],
                group_by=["country"],
                period_comparison=PeriodComparison(grain="quarter"),
                top_k=TopK(measure="growth", k=10, direction=direction),
            ),
        )
        tort = next((r for r in a.rows if r["country"] == "Tortuga"), None)
        assert tort is not None and tort["period_a_value"] < 0  # negative base in the data
        assert tort["growth"] is None  # NULL, not an inverted percentage
        # never the ranked extreme in EITHER direction — a real-growth group leads
        assert a.rows[0]["country"] != "Tortuga" and a.rows[0]["growth"] is not None
    # and the negative base is disclosed AS negative (not as a small base), with the figure
    a = _ans(
        con,
        model,
        QueryIR(
            measures=["net_revenue"],
            group_by=["country"],
            period_comparison=PeriodComparison(grain="quarter"),
            top_k=TopK(measure="growth", k=10),
        ),
    )
    neg = next((x for x in a.assumptions if "NEGATIVE" in x), None)
    assert neg is not None and "Tortuga" in neg and "-294" in neg.replace(",", "")


